CREATE TABLE categories
(
    category_id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    category_name VARCHAR(32)                             NOT NULL,
    max_exercises INTEGER                                 NOT NULL,
    CONSTRAINT pk_categories PRIMARY KEY (category_id)
);

CREATE TABLE confirmation_token
(
    token_id     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    token        VARCHAR(255)                            NOT NULL,
    created_at   TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    expires_at   TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    confirmed_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_confirmationtoken PRIMARY KEY (token_id)
);

CREATE TABLE exercise_categories
(
    exercise_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    CONSTRAINT pk_exercise_categories PRIMARY KEY (exercise_id, category_id)
);

CREATE TABLE exercises
(
    exercise_id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    exercise_name           VARCHAR(255)                            NOT NULL,
    description             VARCHAR(255)                            NOT NULL,
    exercise_thumbnail_link VARCHAR(255),
    exercise_video_link     VARCHAR(255),
    CONSTRAINT pk_exercises PRIMARY KEY (exercise_id)
);

CREATE TABLE roles
(
    role_id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    role_name VARCHAR(255),
    CONSTRAINT pk_roles PRIMARY KEY (role_id)
);

CREATE TABLE testimonials
(
    testimonial_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    author_name    VARCHAR(255)                            NOT NULL,
    author_initial VARCHAR(255),
    author_email   VARCHAR(255)                            NOT NULL,
    testimonial    VARCHAR(1500)                           NOT NULL,
    CONSTRAINT pk_testimonials PRIMARY KEY (testimonial_id)
);

CREATE TABLE user_roles
(
    fk_role_id BIGINT NOT NULL,
    fk_user_id BIGINT NOT NULL
);

CREATE TABLE users
(
    user_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    first_name                VARCHAR(255),
    last_name                 VARCHAR(255),
    email                     VARCHAR(255),
    phone_number              VARCHAR(255),
    password                  VARCHAR(255),
    locked                    BOOLEAN,
    enabled                   BOOLEAN,
    two_factor_authentication BOOLEAN,
    subscribed                BOOLEAN,
    profile_image_link        VARCHAR(255),
    CONSTRAINT pk_users PRIMARY KEY (user_id)
);

